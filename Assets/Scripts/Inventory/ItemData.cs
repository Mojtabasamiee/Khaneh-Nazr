// ═══════════════════════════════════════════════════════════════
//  ItemData.cs — تعریف یک آیتم در بازی (کلید، فیوز، عکس و...)
// ───────────────────────────────────────────────────────────────
//  این کد چه می‌کند؟
//  • یک ScriptableObject است — یعنی «فایل آیتم» می‌سازی نه کد!
//  • برای هر آیتم بازی (کلید سرداب، فیوز، عکس خانوادگی...) یک فایل
//    از این نوع می‌سازی و اسم/توضیح/آیکونش را داخلش پر می‌کنی.
//
//  کجا وصل می‌شود؟
//  • در پنجره‌ی Project: راست‌کلیک → Create → خانه نذر → آیتم بازی
//  • فایل ساخته‌شده را به PickupItem روی شیء داخل صحنه می‌دهی.
// ═══════════════════════════════════════════════════════════════

using UnityEngine;

[CreateAssetMenu(fileName = "NewItem", menuName = "خانه نذر/آیتم بازی")]
public class ItemData : ScriptableObject
{
    [Header("مشخصات آیتم")]
    [Tooltip("شناسه‌ی یکتا — انگلیسی و بدون فاصله! مثلاً key_basement")]
    public string id = "new_item";

    [Tooltip("نام فارسی آیتم که در انبار دیده می‌شود")]
    public string displayName = "آیتم جدید";

    [TextArea(2, 4)]
    [Tooltip("توضیح فارسی — وقتی بازیکن آیتم را بررسی می‌کند")]
    public string description = "توضیحی درباره‌ی این شیء...";

    [Tooltip("آیکون آیتم در انبار (مربع باشد)")]
    public Sprite icon;

    [Header("متن گویندگی هنگام برداشتن (اختیاری)")]
    [Tooltip("شناسه‌ی خط گویندگی از VoiceLibrary که موقع برداشتن پخش شود")]
    public string pickupVoiceId = "";
}
